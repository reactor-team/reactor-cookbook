const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH, args: ['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'] });
  const context = await browser.newContext({ viewport: { width: 1512, height: 982 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.PREVIS_TEST_URL || 'http://localhost:3006');
  await page.getByRole('tab', { name: 'Live rules', exact: true }).click();
  await page.getByText('Set OPENAI_API_KEY on the server to enable monitoring.').waitFor();
  assert.equal(await page.getByRole('button', { name: 'Start monitoring' }).isDisabled(), true);
  await page.screenshot({ path: '/tmp/previs-live-rules.png', fullPage: true });
  console.log('PASS: provider setup and rule editor render without credentials.');
  let calls = [], slow = false;
  await page.route('**/api/observe', async route => {
    if (route.request().method() === 'GET') return route.fulfill({ json: { provider: 'openai', model: 'gpt-6-luna', configured: true, director: true } });
    const data = route.request().postDataJSON(); calls.push(data);
    if (slow) await new Promise(r => setTimeout(r, 1400));
    await route.fulfill({ json: { answers: data.questions.map(q => ({ id: q.id, probability: .99 })), latencyMs: 20, provider: 'openai' } }).catch(() => {});
  });
  await page.evaluate(async () => {
    // A labelled synthetic recording tests pixel capture and timing without a paid model session.
    const canvas = document.createElement('canvas'); canvas.width = 640; canvas.height = 360;
    const ctx = canvas.getContext('2d'); let frame = 0;
    const timer = setInterval(() => { ctx.fillStyle = '#31453b'; ctx.fillRect(0, 0, 640, 360); ctx.fillStyle = '#c7c099'; ctx.fillRect(30 + frame++ % 300, 140, 100, 80); ctx.font = '24px sans-serif'; ctx.fillText('SYNTHETIC TEST VIDEO', 140, 70); }, 33);
    const stream = canvas.captureStream(24); const recorder = new MediaRecorder(stream, { mimeType: 'video/webm' }); const chunks = [];
    recorder.ondataavailable = e => chunks.push(e.data);
    const saved = new Promise(resolve => recorder.onstop = async () => {
      clearInterval(timer); stream.getTracks().forEach(t => t.stop());
      const board = JSON.parse(localStorage.getItem('reactor-storyboard-v21:desert'));
      const db = await new Promise((res, rej) => { const r = indexedDB.open('reactor-studio-takes', 1); r.onsuccess = () => res(r.result); r.onerror = () => rej(r.error); });
      const tx = db.transaction('takes', 'readwrite'); tx.objectStore('takes').put({ id: board.shots[0].id, blob: new Blob(chunks, { type: 'video/webm' }), prompt: 'Synthetic test only.', seconds: 8, createdAt: Date.now() });
      tx.oncomplete = () => { db.close(); resolve(); };
    });
    recorder.start(); await new Promise(r => setTimeout(r, 8000)); recorder.stop(); await saved;
    localStorage.setItem('previs-live-rules-v1', JSON.stringify([{ id: 'test-cue', source: 'scene', condition: 'A yellow rectangle is visible.', action: 'mark', direction: '', enabled: true }]));
  });
  await page.reload();
  await page.getByRole('tab', { name: 'Live rules', exact: true }).click();
  await page.getByRole('button', { name: 'Start monitoring' }).click();
  await page.getByRole('tab', { name: 'Shot', exact: true }).click();
  await page.getByRole('button', { name: 'Replay shot', exact: true }).click();
  await page.waitForTimeout(2800);
  assert.ok(calls.length >= 2); assert.ok(calls.every(c => c.image?.startsWith('data:image/jpeg;base64,')));
  await page.getByRole('tab', { name: 'Live rules', exact: true }).click();
  assert.equal(await page.locator('.watch-event').count(), 1);
  assert.equal(await page.locator('.watch-event img').count(), 1);
  await page.waitForTimeout(1200); assert.equal(await page.locator('.watch-event').count(), 1);
  await page.screenshot({ path: '/tmp/previs-live-rules-trigger.png', fullPage: true });
  console.log('PASS: actual replay pixels sampled; hidden panel stays active; two checks emit one event with evidence.');
  await page.getByRole('button', { name: 'Stop monitoring' }).click();
  await page.getByRole('button', { name: 'Stop playback', exact: true }).click();
  // Slow responses cannot trigger after stopping monitoring.
  await page.getByRole('button', { name: 'Rearm rule', exact: true }).click();
  slow = true; calls = [];
  await page.getByRole('button', { name: 'Start monitoring' }).click();
  await page.getByRole('button', { name: 'Replay shot', exact: true }).click();
  while (calls.length === 0) await page.waitForTimeout(100);
  await page.getByRole('button', { name: 'Stop monitoring' }).click();
  await page.waitForTimeout(1900);
  assert.equal(await page.locator('.watch-event').count(), 1);
  console.log('PASS: stopped monitor ignores an in-flight response.');
  // Feed events use bounded text and queue the operator's direction.
  slow = false;
  await page.getByRole('button', { name: 'Rule JSON', exact: true }).click();
  await page.getByRole('textbox', { name: 'Rule JSON', exact: true }).fill(JSON.stringify([{ id: 'feed-rule', source: 'feed', condition: 'The audience requests rain.', action: 'direct', direction: 'Rain starts falling over the dunes.', enabled: true }]));
  await page.getByRole('button', { name: 'Apply rules', exact: true }).click();
  await page.locator('summary').filter({ hasText: 'External inputs' }).click();
  await page.getByRole('textbox', { name: 'Text or social feed', exact: true }).fill('Audience: make it rain');
  await page.getByRole('button', { name: 'Start monitoring' }).click();
  await page.locator('.watch-pending').waitFor();
  assert.match(await page.locator('.watch-pending').innerText(), /Rain starts falling/);
  assert.ok(calls.some(c => c.source === 'feed' && c.text === 'Audience: make it rain'));
  await page.getByRole('button', { name: 'Stop monitoring' }).click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await page.locator('.watch-pending').count(), 0);
  console.log('PASS: external text triggers a queued director cue; cancellation clears it.');
  // Use Chromium's synthetic webcam, never the machine's actual camera.
  await page.getByRole('button', { name: 'Rule JSON', exact: true }).click();
  await page.getByRole('textbox', { name: 'Rule JSON', exact: true }).fill(JSON.stringify([{ id: 'camera-rule', source: 'webcam', condition: 'A face is visible.', action: 'mark', direction: '', enabled: true }]));
  await page.getByRole('button', { name: 'Apply rules', exact: true }).click();
  await page.getByRole('button', { name: 'Enable webcam', exact: true }).click();
  await page.getByRole('button', { name: 'Turn webcam off', exact: true }).waitFor();
  const camera = await page.locator('.watch-camera').evaluateHandle(video => video.srcObject);
  await page.getByRole('button', { name: 'Start monitoring' }).click();
  await page.waitForFunction(() => document.querySelectorAll('.watch-event').length === 3);
  assert.ok(calls.some(c => c.source === 'webcam' && c.image));
  await page.getByRole('button', { name: 'Stop monitoring' }).click();
  assert.equal(await camera.evaluate(stream => stream.getTracks().every(track => track.readyState === 'ended')), true);
  console.log('PASS: fake webcam frames trigger a rule; stopping releases the camera tracks.');
  await page.getByRole('checkbox', { name: 'Armed', exact: true }).uncheck();
  await page.locator('summary').filter({ hasText: 'Judge the output' }).click();
  await page.getByRole('checkbox', { name: 'Check a visual requirement', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Ask the director to correct the next shot', exact: true }).check();
  await page.getByRole('button', { name: 'Start monitoring' }).click();
  await page.getByRole('button', { name: 'Replay shot', exact: true }).click();
  await page.locator('.watch-pending').waitFor();
  assert.match(await page.locator('.watch-pending').innerText(), /Correct this visual issue/);
  assert.equal(await page.locator('.watch-event').count(), 4);
  await page.getByRole('textbox', { name: 'Text or social feed', exact: true }).fill('A new feed update');
  await page.waitForTimeout(2200);
  assert.equal(await page.locator('.watch-event').count(), 4);
  await page.getByRole('button', { name: 'Stop monitoring' }).click();
  await page.getByRole('button', { name: 'Stop playback', exact: true }).click();
  console.log('PASS: visual judging queues a correction once per clip, even when another input changes.');
  await page.getByRole('checkbox', { name: 'Check a visual requirement', exact: true }).uncheck();
  await page.getByRole('button', { name: 'Rule JSON', exact: true }).click();
  await page.getByRole('textbox', { name: 'Rule JSON', exact: true }).fill(JSON.stringify([{ id: 'stop-rule', source: 'scene', condition: 'A yellow rectangle is visible.', action: 'stop', direction: '', enabled: true }]));
  await page.getByRole('button', { name: 'Apply rules', exact: true }).click();
  await page.getByRole('button', { name: 'Start monitoring' }).click();
  await page.getByRole('button', { name: 'Replay shot', exact: true }).click();
  await page.getByRole('button', { name: 'Start monitoring' }).waitFor();
  assert.equal(await page.locator('.replay-video').count(), 0);
  assert.equal(await page.locator('.watch-event').count(), 5);
  console.log('PASS: stop action stops playback and monitoring.');
  await page.setViewportSize({ width: 800, height: 1000 });
  await page.screenshot({ path: '/tmp/previs-live-rules-narrow.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log('PASS: narrow layout has no horizontal overflow; no browser errors.');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
